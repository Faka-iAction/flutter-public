/// Which credential an operation takes (CONVENTIONS 12.5).
enum AuthMode {
  /// `security: []`: no credential is sent.
  none,

  /// A member's bearer token is required.
  member,

  /// Participation and status operations: the member's bearer token when
  /// signed in, otherwise the guest token in `X-Guest-Token`. Never both.
  participant,

  /// Like [participant], but a guest session is never created for it: used
  /// for reading a guest's own Actions, which a new session cannot see.
  participantRead,
}

class ApiRequest {
  const ApiRequest(
    this.method,
    this.path, {
    this.query = const {},
    this.body,
    this.auth = AuthMode.none,
    this.idempotencyKey,
  });

  final String method;

  /// Operation path below the base URL, starting with `/`. Path parameters
  /// must already be encoded (see [ApiTransport.segment]).
  final String path;
  final Map<String, String> query;
  final Object? body;
  final AuthMode auth;

  /// Sent as `Idempotency-Key` on the operations that require it. Reused,
  /// unchanged, on every automatic retry of this request.
  final String? idempotencyKey;
}

class ApiResponse {
  const ApiResponse({required this.status, required this.body, required this.correlationId, required this.headers});

  final int status;

  /// Decoded JSON, or null for an empty body (`204`).
  final Object? body;
  final String? correlationId;
  final Map<String, String> headers;

  Json get json => throw UnimplementedError('Not published: the implementation is private.');
}

/// The one place HTTP happens. Everything the contract says about requests
/// that is not specific to one operation lives here:
///
/// - `X-Correlation-Id` on every request, generated by the client, kept across
///   automatic retries of one request, and read back from every response;
/// - the error envelope, parsed into [ApiException];
/// - bearer tokens with refresh-token rotation, refreshed by a single flight
///   when several requests find the access token expired at once;
/// - the guest token in `X-Guest-Token`, with a guest session created on first
///   participation and replaced when the server says it is invalid;
/// - automatic retries only where they are safe: `GET`, and requests carrying
///   an `Idempotency-Key`, which is reused unchanged so the server returns the
///   first result instead of doing the work twice.
class ApiTransport {
  ApiTransport({
    required Uri baseUrl,
    required http.Client client,
    required TokenStore tokens,
    required GuestStore guest,
    IdGenerator? ids,
    DateTime Function()? clock,
    Future<void> Function(Duration)? sleep,
    this.timeout = const Duration(seconds: 20),
    this.maxAttempts = 3,
    this.maxAutomaticWait = const Duration(seconds: 5),
  })  : _base = baseUrl,
        _client = client,
        _tokens = tokens,
        _guest = guest,
        _ids = ids ?? IdGenerator(),
        _clock = clock ?? DateTime.now,
        _sleep = sleep ?? ((d) => Future<void>.delayed(d));

  final Uri _base;
  final http.Client _client;
  final TokenStore _tokens;
  final GuestStore _guest;
  final IdGenerator _ids;
  final DateTime Function() _clock;
  final Future<void> Function(Duration) _sleep;
  final Duration timeout;
  final int maxAttempts;

  /// Longest `Retry-After` the transport waits by itself. Longer waits are
  /// returned to the screen as a `429` or `503` for the person to see.
  final Duration maxAutomaticWait;

  final _sessionEnded = StreamController<void>.broadcast();
  Future<StoredTokens?>? _refreshing;
  Future<GuestCredentials>? _creatingGuest;

  /// Fires when the member's session ended on the server side (refresh token
  /// rejected, or the access token revoked). The tokens are already cleared.
  Stream<void> get sessionEnded => throw UnimplementedError('Not published: the implementation is private.');

  IdGenerator get ids => throw UnimplementedError('Not published: the implementation is private.');

  /// Percent-encodes one path segment.
  static String segment(String value) => throw UnimplementedError('Not published: the implementation is private.');

  Future<bool> hasMemberSession() async => throw UnimplementedError('Not published: the implementation is private.');

  Future<void> startMemberSession(TokenPair pair) => throw UnimplementedError('Not published: the implementation is private.');

  Future<void> endMemberSession() => throw UnimplementedError('Not published: the implementation is private.');

  /// Sends [request] and returns its successful response, or throws
  /// [ApiException].
  Future<ApiResponse> send(ApiRequest request) async {
    throw UnimplementedError('Not published: the implementation is private.');
  }

  void dispose() {
    throw UnimplementedError('Not published: the implementation is private.');
  }
}
